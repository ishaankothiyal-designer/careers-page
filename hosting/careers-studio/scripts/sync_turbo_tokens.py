"""Generate CSS from the resolved Turbo UI – Core Figma token snapshot."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT / 'design/turbo-core.tokens.json').read_text())


def css_value(collection, name, value):
    if isinstance(value, bool) or value is None or isinstance(value, dict):
        return None
    if isinstance(value, str):
        if re.fullmatch(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?', value):
            return value
        return json.dumps(value)
    number = f'{value:.6g}'
    if name.startswith('opacity/'):
        return f'{value / 100:.6g}'
    if name.startswith('font/weight/'):
        return number
    if collection == 'Typography' and name.startswith('letter-spacing/'):
        return number + ('em' if name.startswith(('letter-spacing/heading/', 'letter-spacing/display/')) else 'px')
    return number + 'px'


lines = [
    '/* Generated by scripts/sync_turbo_tokens.py. Do not edit values here.',
    '   Source: Turbo UI - Core / skMLeeIF8mbzAT265CI8nP. Theme: Cars24 default.',
    '   Collection and variable names are preserved in CSS custom properties. */',
    ':root {'
]
for collection, group in source['collections'].items():
    lines.append(f'  /* {collection} / {group["mode"]} */')
    for name, value in sorted(group['values'].items()):
        encoded = css_value(collection, name, value)
        if encoded is None:
            continue
        key = re.sub(r'[^a-z0-9-]', '-', f'{collection}-{name}'.lower())
        lines.append(f'  --turbo-{key}: {encoded};')
lines.append('}')
(ROOT / 'app/turbo-tokens.css').write_text('\n'.join(lines) + '\n')
print(f'Generated {sum(line.startswith("  --turbo-") for line in lines)} Turbo Core CSS tokens.')
